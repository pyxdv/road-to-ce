def table(container, rows, headers, widths, small=True):
    t = grid(container, len(rows) + 1, len(headers), widths)
    for i, h in enumerate(headers):
        cell_text(t.rows[0].cells[i], h, bold=True, align="center")
        shade(t.rows[0].cells[i], ACCENT)
    for i, row in enumerate(rows, 1):
        for j, val in enumerate(row):
            cell_text(t.rows[i].cells[j], val, size=SZ_SMALL if small else SZ)
    return t


