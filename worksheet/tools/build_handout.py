def heading(text, en=None):
    para(doc, text, bold=True, color=BLUE, before=14, after=2)
    if en:
        para(doc, en, size=SZ_SMALL, color=GREY, after=4)


def sub(text):
    para(doc, text, bold=True, before=8, after=2)


def twocol(rows, headers, widths, small=True):
    t = grid(doc, len(rows) + 1, len(headers), widths)
    for i, h in enumerate(headers):
        cell_text(t.rows[0].cells[i], h, bold=True, align="center")
        shade(t.rows[0].cells[i], ACCENT)
    for i, row in enumerate(rows, 1):
        for j, val in enumerate(row):
            cell_text(t.rows[i].cells[j], val,
                      size=SZ_SMALL if small else SZ,
                      bold=(j == 0 and len(headers) == 2))
    para(doc, "", after=0)
    return t


def note(label, text):
    b = box(doc)
    rich(b, [(label + "  ", True), (text, False)], before=4, after=4, size=SZ_SMALL)


